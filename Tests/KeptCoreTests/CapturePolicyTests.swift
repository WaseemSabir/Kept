import Testing
@testable import KeptCore

@Suite("Capture policy")
struct CapturePolicyTests {
    let policy = CapturePolicy()

    @Test("Records ordinary text")
    func recordsText() {
        #expect(policy.decision(types: [.string, .rtf], sourceBundleID: "com.apple.TextEdit") == .record)
    }

    @Test("Ignores privacy markers", arguments: [
        (PasteboardType.concealed, IgnoreReason.concealed),
        (.onePasswordLegacy, .concealed),
        (.keeWeb, .concealed),
        (.transient, .transient),
        (.transientLegacy, .transient),
        (.autoGenerated, .autoGenerated),
        (.typeIt4MeClipping, .autoGenerated),
        (.pasteboardGenerator, .autoGenerated),
    ])
    func ignoresMarkers(marker: PasteboardType, reason: IgnoreReason) {
        #expect(policy.decision(types: [.string, marker], sourceBundleID: nil) == .ignore(reason))
    }

    @Test("Ignores Kept's own writes")
    func ignoresOwnWrites() {
        #expect(policy.decision(types: [.string, .keptOwn, .source], sourceBundleID: "app.kept.Kept") == .ignore(.ownWrite))
    }

    @Test("Ignores excluded apps, whatever the case of the bundle ID")
    func ignoresExcludedApps() {
        #expect(policy.decision(types: [.string], sourceBundleID: "com.1password.1password")
            == .ignore(.excludedApp("com.1password.1password")))
        #expect(policy.decision(types: [.string], sourceBundleID: "COM.BITWARDEN.DESKTOP")
            == .ignore(.excludedApp("COM.BITWARDEN.DESKTOP")))

        var settings = CaptureSettings()
        settings.excludedBundleIDs = []
        #expect(CapturePolicy(settings: settings).decision(types: [.string], sourceBundleID: "com.1password.1password") == .record)
    }

    @Test("Ignores Universal Clipboard content only when asked to")
    func remoteClipboardToggle() {
        let types: [PasteboardType] = [.string, .remoteClipboard]
        #expect(policy.decision(types: types, sourceBundleID: nil) == .record)

        let strict = CapturePolicy(settings: CaptureSettings(ignoreRemoteClipboard: true))
        #expect(strict.decision(types: types, sourceBundleID: nil) == .ignore(.remoteClipboard))
        #expect(strict.decision(types: [.string], sourceBundleID: nil) == .record)
    }

    @Test("Ignores everything while paused")
    func ignoresWhilePaused() {
        let paused = CapturePolicy(settings: CaptureSettings(isPaused: true))
        #expect(paused.decision(types: [.string], sourceBundleID: nil) == .ignore(.paused))
    }

    @Test("Ignores pasteboards with nothing Kept stores")
    func ignoresUnsupportedTypes() {
        #expect(policy.decision(types: [], sourceBundleID: nil) == .ignore(.empty))
        let heavy: [PasteboardType] = ["dyn.ah62d4rv4gu8y63n2nuuhg5pbsm4ca6dbsr4gnkduqf31k3pcr7u1e3basv61a3k", "com.apple.webarchive"]
        #expect(policy.decision(types: heavy, sourceBundleID: nil) == .ignore(.empty))
    }

    @Test("Ignores images and files when their capture is off")
    func respectsKindToggles() {
        let noImages = CapturePolicy(settings: CaptureSettings(captureImages: false))
        #expect(noImages.decision(types: [.png, .tiff], sourceBundleID: nil) == .ignore(.kindDisabled(.image)))
        // Office puts a picture next to the text; the text is still recorded.
        #expect(noImages.decision(types: [.string, .png], sourceBundleID: nil) == .record)

        let noFiles = CapturePolicy(settings: CaptureSettings(captureFiles: false))
        #expect(noFiles.decision(types: [.fileURL, .string], sourceBundleID: "com.apple.finder") == .ignore(.kindDisabled(.file)))
    }

    @Test("Prefers the source marker over the frontmost app")
    func resolvesSource() {
        #expect(PasteboardSnapshot.sourceBundleID(marker: "com.agilebits.onepassword7", frontmost: "com.apple.Safari")
            == "com.agilebits.onepassword7")
        #expect(PasteboardSnapshot.sourceBundleID(marker: " ", frontmost: "com.apple.Safari") == "com.apple.Safari")
        #expect(PasteboardSnapshot.sourceBundleID(marker: nil, frontmost: nil) == nil)
    }

    @Test("Decides from a snapshot's items and source")
    func decidesFromSnapshot() {
        // Hand-built snapshots may carry a marker as a representation.
        let snapshot = PasteboardSnapshot(
            items: [item((.string, "secret"), (.concealed, ""))],
            sourceBundleID: "com.example.app"
        )
        #expect(policy.decision(for: snapshot) == .ignore(.concealed))
        #expect(policy.decision(for: textSnapshot("hi", source: "org.keepassxc.keepassxc"))
            == .ignore(.excludedApp("org.keepassxc.keepassxc")))
        #expect(policy.decision(for: textSnapshot("hi", source: "com.apple.Notes")) == .record)
    }

    @Test("Sees markers a reader-shaped snapshot only declares", arguments: [
        (PasteboardType.concealed, IgnoreReason.concealed),
        (.onePasswordLegacy, .concealed),
        (.transient, .transient),
        (.autoGenerated, .autoGenerated),
        (.keptOwn, .ownWrite),
    ])
    func decidesFromDeclaredTypes(marker: PasteboardType, reason: IgnoreReason) {
        // What the app builds: only captured types are read into items, but
        // every declared type is listed.
        let snapshot = PasteboardSnapshot(
            items: [item((.string, "secret"))],
            sourceBundleID: "com.example.app",
            declaredTypes: [.string, marker, .source]
        )
        #expect(snapshot.types == [.string])
        #expect(policy.decision(for: snapshot) == .ignore(reason))

        let remote = PasteboardSnapshot(items: [item((.string, "x"))], declaredTypes: [.string, .remoteClipboard])
        #expect(CapturePolicy(settings: CaptureSettings(ignoreRemoteClipboard: true)).decision(for: remote)
            == .ignore(.remoteClipboard))
    }

    @Test("Reads one image type per item, the cheapest faithful one")
    func prefersCompactImageTypes() {
        #expect(PasteboardType.preferredImageType(in: [.string, .tiff, .png]) == .png)
        #expect(PasteboardType.preferredImageType(in: [.tiff, .jpeg]) == .jpeg)
        #expect(PasteboardType.preferredImageType(in: [.tiff, .heic]) == .heic)
        #expect(PasteboardType.preferredImageType(in: [.tiff, .rtf]) == .tiff)
        #expect(PasteboardType.preferredImageType(in: [.string, .fileURL]) == nil)
    }

    @Test("Defaults the declared types to the items' types")
    func defaultsDeclaredTypes() {
        let snapshot = PasteboardSnapshot(items: [item((.rtf, "{}"), (.string, "a")), item((.string, "b"), (.html, "<b>"))])
        #expect(snapshot.declaredTypes == [.rtf, .string, .html])
        #expect(snapshot.allTypes == [.rtf, .string, .html])
        let declared = PasteboardSnapshot(items: [item((.string, "a"))], declaredTypes: [.concealed])
        #expect(declared.allTypes == [.concealed, .string])
    }
}
