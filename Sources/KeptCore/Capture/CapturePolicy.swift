/// Decides whether a pasteboard change is recorded, from its types and
/// source app alone, before any data is read.
///
/// Reading pasteboard data is what macOS's pasteboard privacy alerts watch,
/// so the app asks the policy first and reads only on `.record`.
public struct CapturePolicy: Sendable {
    public var settings: CaptureSettings

    /// The most pasteboard items one copy may have. Finder writes one item
    /// per file, so this is the most files a clip holds; reading thousands
    /// of items (each one a round trip to the pasteboard server) would stall
    /// the main thread, and a clip that held only some of them would paste
    /// the wrong selection, so bigger copies are skipped (`.tooManyItems`).
    public static let maxItems = 1_000

    public init(settings: CaptureSettings = CaptureSettings()) {
        self.settings = settings
    }

    /// - Parameters:
    ///   - types: the union of types on the pasteboard (`NSPasteboard.types`).
    ///   - sourceBundleID: the resolved source app, see
    ///     `PasteboardSnapshot.sourceBundleID(marker:frontmost:)`.
    public func decision(types: some Sequence<PasteboardType>, sourceBundleID: String?) -> CaptureDecision {
        if settings.isPaused { return .ignore(.paused) }

        let types = Set(types)
        if types.contains(.keptOwn) { return .ignore(.ownWrite) }
        if !types.isDisjoint(with: Self.concealedTypes) { return .ignore(.concealed) }
        if !types.isDisjoint(with: Self.transientTypes) { return .ignore(.transient) }
        if !types.isDisjoint(with: Self.autoGeneratedTypes) { return .ignore(.autoGenerated) }
        if settings.ignoreRemoteClipboard, types.contains(.remoteClipboard) {
            return .ignore(.remoteClipboard)
        }
        if let sourceBundleID, settings.excludes(bundleID: sourceBundleID) {
            return .ignore(.excludedApp(sourceBundleID))
        }

        let captured = types.intersection(PasteboardType.captured)
        if captured.isEmpty { return .ignore(.empty) }
        if !settings.captureFiles, captured.contains(.fileURL) {
            return .ignore(.kindDisabled(.file))
        }
        if !settings.captureImages, captured.isSubset(of: PasteboardType.images) {
            return .ignore(.kindDisabled(.image))
        }
        return .record
    }

    /// The types worth reading from one pasteboard item that offers
    /// `offered`, once the copy is to be recorded: the text types, file URLs
    /// when files are kept, and a single image type
    /// (`PasteboardType.preferredImageType(in:)`) when images are kept.
    /// Everything else, other image formats included, is never read.
    public func typesToRead(offered: some Sequence<PasteboardType>) -> Set<PasteboardType> {
        var types = Set(PasteboardItem.textTypes)
        if settings.captureFiles { types.insert(.fileURL) }
        if settings.captureImages, let image = PasteboardType.preferredImageType(in: offered) {
            types.insert(image)
        }
        return types
    }

    /// The decision for a snapshot that has already been read (tests, and a
    /// final check once the source marker is known). Looks at the
    /// snapshot's `declaredTypes` as well as its items, since the app reads
    /// only captured types and markers never appear among the items.
    public func decision(for snapshot: PasteboardSnapshot) -> CaptureDecision {
        decision(types: snapshot.allTypes, sourceBundleID: snapshot.sourceBundleID)
    }

    static let concealedTypes: Set<PasteboardType> = [.concealed, .onePasswordLegacy, .keeWeb]
    static let transientTypes: Set<PasteboardType> = [.transient, .transientLegacy]
    static let autoGeneratedTypes: Set<PasteboardType> = [
        .autoGenerated, .typeIt4MeClipping, .pasteboardGenerator,
    ]
    /// Markers that mean content must never be recorded, whatever the settings.
    static let privacyMarkers = concealedTypes.union(transientTypes).union(autoGeneratedTypes)
}
