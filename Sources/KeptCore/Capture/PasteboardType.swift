/// A pasteboard type identifier (a UTI string such as `public.rtf`).
///
/// The app converts to and from `NSPasteboard.PasteboardType` by raw value.
public struct PasteboardType: RawRepresentable, Sendable, Hashable, Codable,
    ExpressibleByStringLiteral, CustomStringConvertible
{
    public let rawValue: String

    public init(rawValue: String) {
        self.rawValue = rawValue
    }

    public init(_ rawValue: String) {
        self.rawValue = rawValue
    }

    public init(stringLiteral value: String) {
        self.rawValue = value
    }

    public var description: String { rawValue }

    // MARK: Content Kept captures

    public static let string: PasteboardType = "public.utf8-plain-text"
    public static let rtf: PasteboardType = "public.rtf"
    public static let html: PasteboardType = "public.html"
    public static let png: PasteboardType = "public.png"
    public static let tiff: PasteboardType = "public.tiff"
    public static let jpeg: PasteboardType = "public.jpeg"
    public static let heic: PasteboardType = "public.heic"
    public static let fileURL: PasteboardType = "public.file-url"
    public static let url: PasteboardType = "public.url"

    /// The types Kept reads and stores, in the order it prefers them. The app
    /// reads only these, so heavy types (web archives, Office's OLE data) are
    /// never loaded.
    public static let captured: [PasteboardType] = [
        .string, .rtf, .html, .url, .fileURL, .png, .tiff, .jpeg, .heic,
    ]

    /// Image types, in the order Kept picks the primary image.
    public static let images: [PasteboardType] = [.png, .tiff, .jpeg, .heic]

    /// The one image type to read from an item that offers several: PNG,
    /// then JPEG or HEIC (already compressed), then TIFF (a screenshot's
    /// TIFF can be tens of megabytes; Kept re-encodes it as PNG). Apps put
    /// the same picture in every image type, so reading one is enough.
    /// `nil` when `types` has no image type.
    public static func preferredImageType(in types: some Sequence<PasteboardType>) -> PasteboardType? {
        let offered = Set(types)
        return imageReadingOrder.first { offered.contains($0) }
    }

    private static let imageReadingOrder: [PasteboardType] = [.png, .jpeg, .heic, .tiff]

    // MARK: Markers (nspasteboard.org and Apple)

    /// The bundle ID of the app that wrote the pasteboard (may be empty).
    public static let source: PasteboardType = "org.nspasteboard.source"
    /// Secret content, such as a password.
    public static let concealed: PasteboardType = "org.nspasteboard.ConcealedType"
    /// Content that must never appear in a history.
    public static let transient: PasteboardType = "org.nspasteboard.TransientType"
    /// Content written by an app without user intent.
    public static let autoGenerated: PasteboardType = "org.nspasteboard.AutoGeneratedType"
    /// Content that arrived from another device through Universal Clipboard.
    public static let remoteClipboard: PasteboardType = "com.apple.is-remote-clipboard"
    /// Marks Kept's own writes so they aren't captured again.
    public static let keptOwn: PasteboardType = "app.kept.Kept.own"

    // MARK: Legacy markers, from apps that predate nspasteboard.org

    /// 1Password 7 and earlier (treated as concealed).
    public static let onePasswordLegacy: PasteboardType = "com.agilebits.onepassword"
    /// KeeWeb (treated as concealed).
    public static let keeWeb: PasteboardType = "net.antelle.keeweb"
    /// Peter Maurer's apps, e.g. TextSoap (treated as transient).
    public static let transientLegacy: PasteboardType = "de.petermaurer.TransientPasteboardType"
    /// TypeIt4Me snippet expansion (treated as auto-generated).
    public static let typeIt4MeClipping: PasteboardType = "com.typeit4me.clipping"
    /// Pasteboard generator tools (treated as auto-generated).
    public static let pasteboardGenerator: PasteboardType = "Pasteboard generator type"
}
