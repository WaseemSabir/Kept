/// What to do with a pasteboard change.
public enum CaptureDecision: Sendable, Hashable {
    case record
    case ignore(IgnoreReason)
}

/// Why a pasteboard change wasn't recorded.
public enum IgnoreReason: Sendable, Hashable {
    /// Capture is paused.
    case paused
    /// Kept wrote this content itself.
    case ownWrite
    /// Marked secret (`org.nspasteboard.ConcealedType` or a legacy password type).
    case concealed
    /// Marked as never belonging in a history.
    case transient
    /// Written by an app without user intent.
    case autoGenerated
    /// Came from another device and Universal Clipboard is ignored.
    case remoteClipboard
    /// Copied from an excluded app (the bundle ID).
    case excludedApp(String)
    /// Only images or files, and capturing that kind is turned off.
    case kindDisabled(ClipKind)
    /// More pasteboard items than `CapturePolicy.maxItems` (thousands of
    /// files selected in Finder, say).
    case tooManyItems
    /// Nothing Kept captures: no types, or only types it skips.
    case empty
}
